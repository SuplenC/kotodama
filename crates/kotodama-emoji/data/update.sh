#!/usr/bin/env bash
# Rewrites emoji.tsv, the data the emoji Bundled extension is built with, from
# Unicode's emoji-test.txt, CLDR's English annotations and keys.tsv.
#
# emoji.tsv has one line per character: the character, its CLDR name, its CLDR
# keywords not already words of the name, separated by `|`, and, for an emoji
# with skin tones, its five toned forms from light to dark, separated by
# spaces. Emoji come first, in CLDR order; then the symbols CLDR names that
# aren't emoji or ASCII, such as arrows and math; then the keys of keys.tsv
# CLDR leaves out. A key CLDR has, such as ⇧ or ⏏, keeps its CLDR name and gains
# keys.tsv's keywords.
#
# Usage: data/update.sh (from anywhere; needs curl and awk)
set -euo pipefail

# Kept in step: CLDR 48 annotates Emoji 17.
emoji_version=17.0.0
cldr_tag=release-48

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

curl -sSfL -o "$tmp/emoji-test.txt" "https://unicode.org/Public/$emoji_version/emoji/emoji-test.txt"
cldr=https://raw.githubusercontent.com/unicode-org/cldr/$cldr_tag/common
curl -sSfL -o "$tmp/annotations.xml" "$cldr/annotations/en.xml"
curl -sSfL -o "$tmp/derived.xml" "$cldr/annotationsDerived/en.xml"

{
    printf '# Generated by update.sh from Unicode Emoji %s and CLDR %s (Unicode-3.0, see LICENSE-UNICODE), plus keys.tsv.\n' "$emoji_version" "$cldr_tag"
    LC_ALL=C awk -F'\t' '
        function unescape(s) {
            gsub(/&lt;/, "<", s); gsub(/&gt;/, ">", s); gsub(/&quot;/, "\"", s)
            gsub(/&apos;/, "\047", s); gsub(/&amp;/, "\\&", s)
            return s
        }
        # The keywords of `list` (separated by " | ") that are not words of
        # `name`, nor already in `kept`, joined by "|".
        function keywords(list, name, kept,    words, n, i, w, parts, m, j, seen, out) {
            n = split(tolower(name), words, /[ :,]+/)
            for (i = 1; i <= n; i++) seen[words[i]] = 1
            out = ""
            m = split(kept, parts, /\|/)
            for (j = 1; j <= m; j++) { seen[parts[j]] = 1; out = out (out == "" ? "" : "|") parts[j] }
            m = split(list, parts, / \| /)
            for (j = 1; j <= m; j++) {
                w = parts[j]
                if (w == "" || (w in seen)) continue
                seen[w] = 1
                out = out (out == "" ? "" : "|") w
            }
            return out
        }
        BEGIN {
            fe0f = "\357\270\217"
            tone["light"] = 1; tone["medium-light"] = 2; tone["medium"] = 3
            tone["medium-dark"] = 4; tone["dark"] = 5
        }
        FILENAME ~ /keys\.tsv$/ {
            keys[++nkeys] = $1; keyname[$1] = $2; keykw[$1] = $3
            next
        }
        /<annotation cp=/ {
            line = $0
            sub(/^[ \t]*<annotation cp="/, "", line)
            cp = line; sub(/".*/, "", cp); cp = unescape(cp)
            text = line; sub(/^[^>]*>/, "", text); sub(/<\/annotation>.*/, "", text)
            text = unescape(text)
            if (line ~ /^[^>]*type="tts"/) name[cp] = text
            else annotated[cp] = text
            if (FILENAME ~ /annotations\.xml$/ && !(cp in listed)) { listed[cp] = 1; symbols[++nsymbols] = cp }
            next
        }
        FILENAME ~ /emoji-test\.txt$/ && /^[0-9A-F]/ {
            status = $0; sub(/^[^;]*; */, "", status); sub(/ .*/, "", status)
            rest = substr($0, index($0, "# ") + 2)
            e = rest; sub(/ .*/, "", e)
            nm = rest; sub(/^[^ ]* E[0-9.]+ /, "", nm)
            bare = e; gsub(fe0f, "", bare)
            emoji[bare] = 1
            if (status != "fully-qualified") next
            if (nm ~ /skin tone/) {
                # One tone for the whole emoji, as in "thumbs up: dark skin
                # tone" or "kiss: woman, man, dark skin tone", is a toned form
                # of the emoji named by what comes before it. Mixed tones are
                # left out.
                if (match(nm, /(: |, )(light|medium-light|medium|medium-dark|dark) skin tone$/)) {
                    base = substr(nm, 1, RSTART - 1)
                    t = substr(nm, RSTART + 2); sub(/ skin tone$/, "", t)
                    if (base !~ /skin tone/ && (base in byname)) tones[byname[base], tone[t]] = e
                }
                next
            }
            byname[nm] = ++nemoji
            chars[nemoji] = e; names[nemoji] = nm
            next
        }
        END {
            for (i = 1; i <= nemoji; i++) {
                e = chars[i]; bare = e; gsub(fe0f, "", bare)
                toned = ""
                if ((i SUBSEP 5) in tones)
                    for (t = 1; t <= 5; t++) toned = toned (t > 1 ? " " : "") tones[i, t]
                kw = keywords(annotated[bare], names[i], "")
                if (bare in keyname) { kw = keywords(keykw[bare], names[i], kw); done[bare] = 1 }
                print e "\t" names[i] "\t" kw "\t" toned
            }
            for (i = 1; i <= nsymbols; i++) {
                cp = symbols[i]
                if ((cp in emoji) || length(cp) <= 1 || !(cp in name)) continue
                kw = keywords(annotated[cp], name[cp], "")
                if (cp in keyname) { kw = keywords(keykw[cp], name[cp], kw); done[cp] = 1 }
                print cp "\t" name[cp] "\t" kw "\t"
            }
            for (i = 1; i <= nkeys; i++) {
                cp = keys[i]
                if (cp in done) continue
                print cp "\t" keyname[cp] "\t" keywords(keykw[cp], keyname[cp], "") "\t"
            }
        }
    ' "$here/keys.tsv" "$tmp/annotations.xml" "$tmp/derived.xml" "$tmp/emoji-test.txt"
} >"$here/emoji.tsv"
